import { IncomeSeriesEndReason, InvestmentIncomeType } from '@investment/domain/enum';
import { IncomeSeriesFrequency } from '@investment/domain/service/IncomeSeriesSchedule';

// Spec 115: a recurring income of an asset. Dates `YYYY-MM-DD`, `amountPerUnit` a decimal string.
export interface IncomeSeriesEntity {
  accountId: null | string;
  amountPerUnit: string;
  assetId: string;
  categoryId: null | string;
  createdBy: string;
  currency: string;
  endDate: null | string;
  endedAt: null | string;
  endReason: IncomeSeriesEndReason | null;
  exDateOffsetDays: null | number;
  firstNumber: number;
  firstPaymentDate: string;
  frequency: IncomeSeriesFrequency;
  id: string;
  lastGeneratedNumber: number;
  notes: null | string;
  type: InvestmentIncomeType;
  withFinance: boolean;
}
// An occurrence to insert as a real income (FR 14-15, 18-19).
export interface OccurrenceInsert {
  exDate: string;
  netAmount: number;
  number: number;
  paymentDate: string;
  quantity: string;
  received: boolean;
}
// What a series row stores when it is created (the id is generated by the datasource).
export interface CreateSeriesParams {
  assetLabel: string;
  occurrences: OccurrenceInsert[];
  series: NewIncomeSeries;
}
export type NewIncomeSeries = Omit<IncomeSeriesEntity, 'id'>;
// Header fields an edit can change (ALL scope and reopen, FR 24, 26).
export interface PlannedRewrite {
  amountPerUnit: string;
  exDate: string;
  incomeId: string;
  netAmount: number;
  quantity: string;
}
export interface SeriesPatch {
  accountId?: null | string;
  amountPerUnit?: string;
  categoryId?: null | string;
  endDate?: null | string;
  endedAt?: null | string;
  endReason?: IncomeSeriesEndReason | null;
  lastGeneratedNumber?: number;
  notes?: null | string;
  withFinance?: boolean;
}
